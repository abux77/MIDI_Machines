#!/usr/bin/env python3
"""Prepare full user recordings for the web synth; originals remain untouched."""
import array, hashlib, json, math, subprocess, wave
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SOURCE=Path.home()/'Downloads'
DEST=ROOT/'web/assets/synth'
SPECS=[
 ('gritty-bass-wide_112bpm_C_major.wav','Gritty wide bass',24,24),
 ('gritty-distorted-808-bass_120bpm_E_major.wav','Gritty 808 bass',28,24),
 ('prophet-keys-chords-falling_156bpm_G_major.wav','Prophet falling chords (C major)',None,48),
 ('prophet-key-wobble-note_E_major.wav','Prophet wobble note',40,36),
 ('prophet-wobbling-synth-key_162bpm_C_major.wav','Prophet wobbling key',60,60),
]
def pitch(path,note):
 raw=subprocess.check_output(['ffmpeg','-v','error','-ss','0.2','-t','0.5','-i',str(path),'-ar','44100','-ac','1','-f','f32le','-'])
 samples=array.array('f');samples.frombytes(raw)
 expected=44100/(440*2**((note-69)/12));lags=range(int(expected*.96),int(expected*1.04)+2)
 scores=[]
 for lag in lags:
  a=samples[:-lag];b=samples[lag:]
  scores.append(sum(x*y for x,y in zip(a,b))/math.sqrt(sum(x*x for x in a)*sum(y*y for y in b)))
 i=max(range(1,len(scores)-1),key=scores.__getitem__)
 delta=.5*(scores[i-1]-scores[i+1])/(scores[i-1]-2*scores[i]+scores[i+1])
 return 44100/(lags[i]+delta),scores[i]
entries=[]
for filename,name,source_note,root_note in SPECS:
 source=SOURCE/filename;out='user-'+filename
 if source_note is None:
  ratio=2**(5/12);hz=None;confidence=None
 else:
  hz,confidence=pitch(source,source_note)
  ratio=(440*2**((root_note-69)/12))/hz
 for attempt in range(5):
  subprocess.run(['ffmpeg','-v','error','-y','-i',str(source),'-af',f'aresample=44100,asetrate={round(44100*ratio)},aresample=44100,alimiter=limit=0.9:level=false','-ar','44100','-ac','2','-c:a','pcm_s16le',str(DEST/out)],check=True)
  if source_note is None:break
  tuned_hz,_=pitch(DEST/out,root_note)
  target=440*2**((root_note-69)/12)
  cents=1200*math.log2(tuned_hz/target)
  if abs(cents)<5:break
  ratio*=target/tuned_hz
 if source_note is not None and abs(cents)>=10:
  raise RuntimeError(f'{name}: tuning verification failed ({cents:.1f} cents)')
 with wave.open(str(DEST/out)) as wav:frames=wav.getnframes()
 entries.append(dict(name=name,file=out,frames=frames,sampleRate=44100,rootNote=root_note,oneShot=True,sourceFile=filename,sourceSha256=hashlib.sha256(source.read_bytes()).hexdigest(),measuredSourceHz=hz,pitchConfidence=confidence,pitchRatio=ratio,verifiedCentsFromC=None if source_note is None else cents,tuningBasis='labeled G major to C major (+5 semitones)' if hz is None else 'autocorrelation near labeled note; tuned to equal-tempered C (A4=440 Hz)'))
 print(name,'ratio',round(ratio,6),'source Hz',hz)
(ROOT/'samples/synth/user-manifest.json').write_text(json.dumps(entries,indent=2)+'\n')
(ROOT/'web/user-synth-samples.js').write_text('// User-provided recordings; generated by tools/import_user_synth.py.\nexport const userSynthSamples='+json.dumps(entries)+';\n')
