#!/usr/bin/env python3
"""Embed the active web palette in flash: Bass cycle + four full mono recordings."""
from pathlib import Path
import array,json,math,subprocess,wave
root=Path(__file__).resolve().parents[1]
entries=[dict(file='AKWF_ebass_0001.wav',rootNote=None,sampleRate=44100)]+[entry for entry in json.loads((root/'samples/synth/user-manifest.json').read_text()) if 'falling' not in entry['file']]
header=['// Generated by tools/embed_hardware_synth.py. User recordings are not CC0.','#pragma once','#include <stdint.h>','typedef struct {const int16_t *pcm;uint32_t frames;unsigned rate,root;int loop;} synth_sample_t;']
metadata=[];increments=[];total=0
for index,entry in enumerate(entries):
 if index==0:
  with wave.open(str(root/'samples/synth'/entry['file'])) as wav:
   pcm=array.array('h');pcm.frombytes(wav.readframes(wav.getnframes()));rate=wav.getframerate()
 else:
  raw=subprocess.check_output(['ffmpeg','-v','error','-i',str(root/'web/assets/synth'/entry['file']),'-ac','1','-ar','22050','-f','s16le','-'])
  pcm=array.array('h');pcm.frombytes(raw);rate=22050
 total+=len(pcm)*2
 header.append(f'static const int16_t hardware_pcm_{index}[]={{'+','.join(map(str,pcm))+'};')
 metadata.append('{hardware_pcm_%d,%d,%d,%d,%d}'%(index,len(pcm),rate,entry['rootNote'] or 0,index==0))
 increments.append('{'+','.join(str(round((440*2**((note-69)/12)*len(pcm)/44100 if index==0 else rate/44100*2**((note-entry['rootNote'])/12))*65536)) for note in range(128))+'}')
header+=['static const synth_sample_t synth_samples[5]={'+','.join(metadata)+'};','static const uint32_t hardware_increments[5][128]={'+','.join(increments)+'};']
(root/'core/hardware_synth_data.h').write_text('\n'.join(header)+'\n')
print('Hardware PCM:',total,'bytes; five sounds, full recordings, 22.05 kHz mono.')
