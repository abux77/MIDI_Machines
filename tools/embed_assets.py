"""Regenerate C assets from the preserved v0.6 maps and factory WAVs."""
import ast
import json
import shutil
import wave
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
tree = ast.parse((ROOT/'data/grids_data.py').read_text())
nodes = next(ast.literal_eval(n.value) for n in tree.body if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id=='NODES' for t in n.targets))
assert len(nodes)==25 and all(len(n)==96 for n in nodes)
(ROOT/'core/grids_data.h').write_text('// Copyright Emilie Gillet / Mutable Instruments. GPL-3.0-or-later.\nstatic const unsigned char nodes[25][96] = {\n'+',\n'.join('{'+','.join(map(str,n))+'}' for n in nodes)+'\n};\n')
names = [f'{voice}{slot:02}' for slot in range(1, 9) for voice in ('BD', 'SD', 'HH')]
for name in names:
    with wave.open(str(ROOT/'samples'/f'{name}.WAV')) as wav:
        if (wav.getnchannels(), wav.getsampwidth(), wav.getframerate(), wav.getcomptype()) != (1, 2, 44100, 'NONE'):
            raise ValueError(f'{name}: expected mono 16-bit 44100 Hz PCM')
(ROOT/'web/assets').mkdir(exist_ok=True)
for name in names:
    shutil.copyfile(ROOT/'samples'/f'{name}.WAV', ROOT/'web/assets'/f'{name}.WAV')
(ROOT/'web/samples.js').write_text('// Generated by tools/embed_assets.py.\nexport const sampleLibrary = '+json.dumps([[f'{voice}{slot:02}.WAV' for slot in range(1, 9)] for voice in ('BD', 'SD', 'HH')])+';\n')
header='#pragma once\n#include <stdint.h>\n'
for name in names:
    data=(ROOT/'samples'/f'{name}.WAV').read_bytes()
    header+=f'static const uint8_t factory_{name}[] = {{'+','.join(map(str,data))+'};\n'
header+='typedef struct {const char *name; const uint8_t *data; unsigned size;} factory_t;\nstatic const factory_t factory[] = {\n'+',\n'.join(f'{{"{n}.WAV",factory_{n},sizeof(factory_{n})}}' for n in names)+'};\n'
(ROOT/'src/factory.h').write_text(header)
