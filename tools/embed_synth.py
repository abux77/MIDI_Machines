#!/usr/bin/env python3
"""Embed the licensed single-cycle WAVs and fixed-point pitch increments."""
import json, struct, wave, shutil
from pathlib import Path
root=Path(__file__).resolve().parents[1]
folder=root/'samples/synth'
manifest=json.loads((folder/'manifest.json').read_text())
arrays=[]
for entry in manifest:
    with wave.open(str(folder/entry['file'])) as wav:
        assert wav.getnchannels()==1 and wav.getsampwidth()==2
        frames=wav.getnframes()
        assert frames==600
        pcm=struct.unpack('<'+'h'*frames,wav.readframes(frames))
        entry.update(frames=frames,sampleRate=wav.getframerate(),loopStart=0,loopEnd=frames)
    arrays.append('{'+','.join(map(str,pcm))+'}')
    (root/'web/assets/synth').mkdir(parents=True,exist_ok=True)
    shutil.copyfile(folder/entry['file'],root/'web/assets/synth'/entry['file'])
header='// Adventure Kid Waveforms, Kristoffer Ekstrand, CC0-1.0. Generated by tools/embed_synth.py.\n#pragma once\n#include <stdint.h>\n'
header+='static const int16_t synth_waves[4][600]={'+',\n'.join(arrays)+'};\n'
increments=[round(440*2**((n-69)/12)*600*65536/44100) for n in range(128)]
header+='static const uint32_t synth_increments[128]={'+','.join(map(str,increments))+'};\n'
(root/'core/synth_data.h').write_text(header)
(root/'web/synth-samples.js').write_text('// CC0-1.0 waveform metadata; generated by tools/embed_synth.py.\nexport const synthSamples='+json.dumps(manifest)+';\n')
print('Embedded four 600-frame waveforms; complete cycle loop points 0–600.')
